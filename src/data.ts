// Helper to safely load data from localStorage
export function loadFromStorage<T>(key: string, defaultValue: T): T {
  try {
    const item = localStorage.getItem(`artsportal_${key}`);
    const parsed = item ? JSON.parse(item) : null;
    if (key === 'programmes' && Array.isArray(parsed) && parsed.length < 50) {
      return defaultValue;
    }
    return (parsed !== null && parsed !== undefined) ? parsed : defaultValue;
  } catch (error) {
    console.warn(`Error reading localStorage key "${key}":`, error);
    return defaultValue;
  }
}

// Helper to save data to localStorage and sync to backend
export function saveToStorage<T>(key: string, value: T): void {
  try {
    localStorage.setItem(`artsportal_${key}`, JSON.stringify(value));
    
    // Sync to central backend
    if (typeof window !== 'undefined') {
      clearTimeout((window as any)._syncTimer);
      (window as any)._syncTimer = setTimeout(() => {
        const state = {
           programmes: loadFromStorage('programmes', DEFAULT_PROGRAMMES),
           teams: (window as any)._currentTeams || DEFAULT_TEAMS,
           users: loadFromStorage('users', DEFAULT_USERS),
           results: (window as any)._currentResults || DEFAULT_RESULTS,
           appeals: loadFromStorage('appeals', DEFAULT_APPEALS),
           feedback: loadFromStorage('feedback', DEFAULT_FEEDBACK),
           announcements: loadFromStorage('announcements', DEFAULT_ANNOUNCEMENTS),
           settings: loadFromStorage('settings', DEFAULT_SETTINGS),
           security: loadFromStorage('security', DEFAULT_SECURITY),
           auditLogs: loadFromStorage('auditLogs', DEFAULT_AUDIT_LOGS),
           evaluations: (window as any)._currentEvaluations || [],
           muallims: (window as any)._currentMuallims || loadFromStorage('muallims', initialMuallims),
           committee: (window as any)._currentCommittee || loadFromStorage('committee', initialCommittee)
        };
        (state as any)[key] = value as any;

        fetch('/api/state', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(state)
        }).catch(e => console.warn('Sync failed:', e));
      }, 300);
    }
  } catch (error) {
    console.warn(`Error writing localStorage key "${key}":`, error);
  }
}

// Global data states and sync
export interface Database {
  programmes: Programme[];
  teams: Team[];
  users: UserProfile[];
  results: PublishedResult[];
  appeals: Appeal[];
  feedback: Feedback[];
  announcements: Announcement[];
  settings: SystemSettings;
  security: SecurityConfig;
  auditLogs: AuditLog[];
  muallims: Muallim[];
  committee: CommitteeMember[];
}

export function initializeDatabase(): Database {
  const programmes = loadFromStorage<Programme[]>('programmes', DEFAULT_PROGRAMMES);
  const teams = loadFromStorage<Team[]>('teams', DEFAULT_TEAMS);
  const usersRaw = loadFromStorage<UserProfile[]>('users', DEFAULT_USERS);
  const users = (Array.isArray(usersRaw) && usersRaw.length >= 200) ? usersRaw : DEFAULT_USERS;
  const muallims = loadFromStorage<Muallim[]>('muallims', initialMuallims);
  const committee = loadFromStorage<CommitteeMember[]>('committee', initialCommittee);
  
  
  let results = loadFromStorage<PublishedResult[]>('results', DEFAULT_RESULTS);

  // Auto-clean stale legacy test data from local storage if present
  const hasLegacyDummy = Array.isArray(results) && results.some(r => r.programmeId === 'prog_001' || r.rankings?.some(rk => rk.teamId === 'team_blue'));
  if (hasLegacyDummy || !results || results.length === 0) {
    results = DEFAULT_RESULTS;
    saveToStorage('results', DEFAULT_RESULTS);
  }
  const appeals = loadFromStorage<Appeal[]>('appeals', DEFAULT_APPEALS);
  const feedback = loadFromStorage<Feedback[]>('feedback', DEFAULT_FEEDBACK);
  const announcements = loadFromStorage<Announcement[]>('announcements', DEFAULT_ANNOUNCEMENTS);
  const settings = loadFromStorage<SystemSettings>('settings', DEFAULT_SETTINGS);
  const security = loadFromStorage<SecurityConfig>('security', DEFAULT_SECURITY);
  const auditLogs = loadFromStorage<AuditLog[]>('auditLogs', DEFAULT_AUDIT_LOGS);

  // Recalculate scoreboard dynamically based on published results
  const teamScoreMap: Record<string, number> = {};
  teams.forEach(t => {
    teamScoreMap[t.id] = 0;
  });

  results.forEach(res => {
    const prog = programmes.find(p => p.id === res.programmeId);
    const isPublished = prog ? (prog.resultPublished === true) : (res.locked === true);
    if (!isPublished) return;

    const isGirlsProg = prog ? (prog.categoryGroup ? prog.categoryGroup.toLowerCase().includes('girls') : false) : false;

    res.rankings.forEach(ranking => {
      let targetTeamId = ranking.teamId;

      // Automatic routing for group team IDs to Boys/Girls division
      if (targetTeamId === 'diraya') {
        targetTeamId = isGirlsProg ? 'diraya_girls' : 'diraya_boys';
      } else if (targetTeamId === 'furooha') {
        targetTeamId = isGirlsProg ? 'furooha_girls' : 'furooha_boys';
      } else if (targetTeamId === 'swaraha') {
        targetTeamId = isGirlsProg ? 'swaraha_girls' : 'swaraha_boys';
      }

      if (teamScoreMap[targetTeamId] !== undefined) {
        teamScoreMap[targetTeamId] += (ranking.points || 0);
      }
    });
  });

  const updatedTeams = teams.map(t => ({
    ...t,
    points: teamScoreMap[t.id] || 0
  }));

  // Store back
  saveToStorage('teams', updatedTeams);

  return {
    programmes,
    teams: updatedTeams,
    users,
    results,
    appeals,
    feedback,
    announcements,
    settings,
    security,
    auditLogs,
    muallims,
    committee
  };
}
